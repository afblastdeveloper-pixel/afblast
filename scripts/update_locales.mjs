// Tambahkan fallback untuk ar, zh, th, fil jika belum ada
;['ar', 'zh', 'th', 'fil'].forEach((l) => {
  translations[l] = translations.en // default fallback will be enhanced
})

const rootDir = 'src/i18n/locales'
for (const loc of ['id', 'en', 'ar', 'zh', 'th', 'fil']) {
  const filePath = path.join(rootDir, `${loc}.json`)
  if (!fs.existsSync(filePath)) continue
  const existing = JSON.parse(fs.readFileSync(filePath, 'utf8'))
  const update = translations[loc] || translations.en
  for (const k of Object.keys(update)) {
    existing[k] = Object.assign({}, existing[k] || {}, update[k])
  }
  fs.writeFileSync(filePath, JSON.stringify(existing, null, 2), 'utf8')
  console.log(`Updated ${loc}.json`)
}
